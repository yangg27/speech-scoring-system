-- =============================================================================
-- 演讲比赛评分系统 · 数据库初始化脚本
-- 适用：WorkBuddy 云服务（Serverless PostgreSQL + PostgREST）
--
-- 执行方式（二选一）：
--   A. 在 WorkBuddy 对话中让 AI 助手依次执行本文件的每条语句
--   B. 云服务控制台的 SQL 编辑器逐条执行
--
-- 注意：PostgREST 场景下「建表」与「授权」是两道独立的门，缺一不可：
--   ① GRANT  —— 把表权限授给 anon / authenticated 角色
--   ② POLICY —— 创建 RLS 策略放行
--   只做其中一步会得到 42501 (权限不足) 错误。
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. events —— 活动表（活动名称、评分维度、计分规则、状态）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text        NOT NULL,
  admin_pin    text        NOT NULL DEFAULT 'admin888',
  -- 评分维度：数组，每项 { id, name, max, weight, group?, standard? }
  -- 例：[{"id":"d1","name":"主题内容","max":30,"weight":1}]
  dimensions   jsonb       NOT NULL DEFAULT '[]'::jsonb,
  -- 活动设置：计分规则 / 评委名单 / 已移除评委 / 防代打开关
  -- 例：{"dropHighest":false,"dropLowest":true,"dropCount":2,
  --      "judgeRoster":[{"name":"张三","dept":"研发中心"}],
  --      "excludedJudges":[],"deviceLock":true}
  settings     jsonb       NOT NULL DEFAULT '{"dropCount": 1, "dropLowest": false, "dropHighest": false}'::jsonb,
  -- 活动状态：draft(筹备中) / open(接收评分) / closed(已结束)
  status       text        NOT NULL DEFAULT 'draft',
  created_at   timestamptz NOT NULL DEFAULT now()
);


-- -----------------------------------------------------------------------------
-- 2. speakers —— 选手表
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS speakers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    bigint      NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  seq         integer     NOT NULL DEFAULT 1,      -- 出场顺序（评分序号）
  name        text        NOT NULL,
  department  text,                                 -- 单位/部门（可选）
  group_name  text        DEFAULT '',               -- 分组名（可选，用于分轮次/分组）
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS speakers_event_id_idx ON speakers(event_id);


-- -----------------------------------------------------------------------------
-- 3. scores —— 评分记录表
--    meta 字段用于防代打分的留痕（设备指纹 / IP / 切换记录）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS scores (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    bigint      NOT NULL REFERENCES events(id)    ON DELETE CASCADE,
  speaker_id  bigint      NOT NULL REFERENCES speakers(id)  ON DELETE CASCADE,
  judge_name  text        NOT NULL,
  -- 各维度得分：{"d1":25,"d2":20,...}
  scores      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  comment     text,
  -- 留痕：{"device_id":"...","ip":"...","loc":"...","ua":"...",
  --        "from_judge":"...","switched_at":"...","switch_approved":false}
  meta        jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  -- 同一位评委对同一位选手只保留一条记录（重复提交走更新）
  CONSTRAINT scores_event_id_speaker_id_judge_name_key
    UNIQUE (event_id, speaker_id, judge_name)
);

CREATE INDEX IF NOT EXISTS scores_event_id_idx   ON scores(event_id);
CREATE INDEX IF NOT EXISTS scores_speaker_id_idx ON scores(speaker_id);


-- -----------------------------------------------------------------------------
-- 4. app_config —— 全局配置表（管理口令等）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS app_config (
  cfg_key     text        PRIMARY KEY,
  cfg_value   text,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- 初始化管理口令（可按需修改）
INSERT INTO app_config (cfg_key, cfg_value)
VALUES ('admin_pin', 'admin888')
ON CONFLICT (cfg_key) DO NOTHING;


-- =============================================================================
-- 5. 授权 + RLS 策略（两道门都要做）
--    本项目为「匿名可读写」场景（评委扫码免登录），故策略为全放行。
--    生产环境如担心被扫库，可把 anon 的权限收窄为「只读 speakers/events，
--    只写 scores」，再配合服务端校验。
-- =============================================================================

-- ---- 门 ①：GRANT ----
GRANT SELECT, INSERT, UPDATE, DELETE ON events     TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON speakers   TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON scores     TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON app_config TO anon, authenticated;
-- 使用 IDENTITY 自增列时无需额外授权 sequence；若改用 SERIAL 请补：
-- GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- ---- 门 ②：ROW LEVEL SECURITY 策略 ----
ALTER TABLE events     ENABLE ROW LEVEL SECURITY;
ALTER TABLE speakers   ENABLE ROW LEVEL SECURITY;
ALTER TABLE scores     ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_config ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS events_all     ON events;
DROP POLICY IF EXISTS speakers_all   ON speakers;
DROP POLICY IF EXISTS scores_all     ON scores;
DROP POLICY IF EXISTS app_config_all ON app_config;

CREATE POLICY events_all     ON events     FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY speakers_all   ON speakers   FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY scores_all     ON scores     FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY app_config_all ON app_config FOR ALL USING (true) WITH CHECK (true);

